// ruleFor returns the declarations of every rule in a stylesheet whose
// selector list names `sel` exactly, joined — comments stripped first.
function ruleFor(sheet, sel) {
    const bare = sheet.replace(/\/\*[\s\S]*?\*\//g, '');
    let out = '';
    for (const r of bare.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
        if (r[1].split(',').map(x => x.trim().replace(/\s+/g, ' ')).includes(sel)) out += r[2] + ';';
    }
    return out;
}

