// ── a small DOM ─────────────────────────────────────────────────────────────
//
// Enough of one to put the picture's markup in a tree and dispatch a click
// that BUBBLES from the element it is dispatched at: parentNode, dataset,
// getAttribute, closest over the selectors the hosts use, and listeners that
// see e.target and can stop propagation. The markup is generated by this
// file's renderer and is well formed, so a tokenizer is a parser here.

class Node {
    constructor(tag, attrs, parent) {
        this.tagName = tag;
        this.attrs = attrs || {};
        this.parentNode = parent || null;
        this.children = [];
        this.listeners = {};
        this.dataset = {};
        for (const k of Object.keys(this.attrs)) {
            if (k.startsWith('data-')) {
                this.dataset[k.slice(5).replace(/-([a-z])/g, (_, c) => c.toUpperCase())] = this.attrs[k];
            }
        }
    }
    getAttribute(k) { return k in this.attrs ? this.attrs[k] : null; }
    get id() { return this.attrs.id || ''; }
    classList() { return (this.attrs.class || '').split(/\s+/).filter(Boolean); }
    matches(sel) {
        sel = sel.trim();
        const sp = sel.lastIndexOf(' ');
        if (sp > 0) {
            if (!this.matches(sel.slice(sp + 1))) return false;
            const up = sel.slice(0, sp);
            for (let p = this.parentNode; p; p = p.parentNode) if (p.matches(up)) return true;
            return false;
        }
        if (sel.startsWith('#')) return this.id === sel.slice(1);
        const attr = /^\[([\w-]+)\]$/.exec(sel);
        if (attr) return attr[1] in this.attrs;
        return false;
    }
    closest(sel) {
        for (let n = this; n; n = n.parentNode) if (n.matches(sel)) return n;
        return null;
    }
    addEventListener(type, fn) { (this.listeners[type] = this.listeners[type] || []).push(fn); }
    dispatchEvent(e) {
        e.target = this;
        let stopped = false;
        e.stopPropagation = () => { stopped = true; };
        for (let n = this; n && !(stopped && n !== this); n = n.parentNode) {
            if (!e.bubbles && n !== this) break;
            for (const fn of (n.listeners[e.type] || [])) fn(e);
            if (stopped) break;
        }
        return true;
    }
    all(pred, out) {
        out = out || [];
        for (const c of this.children) { if (pred(c)) out.push(c); c.all(pred, out); }
        return out;
    }
}

function parse(markup, root) {
    const re = /<(\/?)([\w:-]+)((?:\s+[\w:-]+="[^"]*")*)\s*(\/?)>/g;
    let cur = root, mm;
    while ((mm = re.exec(markup))) {
        if (mm[1]) { cur = cur.parentNode; continue; }
        const attrs = {};
        for (const a of mm[3].matchAll(/([\w:-]+)="([^"]*)"/g)) {
            // A DUPLICATE ATTRIBUTE IS DROPPED, the way the HTML parser drops
            // it: the first one wins.
            if (!(a[1] in attrs)) attrs[a[1]] = a[2];
        }
        const n = new Node(mm[2], attrs, cur);
        cur.children.push(n);
        if (!mm[4]) cur = n;
    }
    if (cur !== root) throw new Error('unbalanced markup');
    return root;
}

function click(node) {
    node.dispatchEvent({ type: 'click', bubbles: true });
}

