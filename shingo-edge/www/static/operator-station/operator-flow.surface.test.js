// dashed, and tapping one is how a position joins the flow.
//
// The handler is composer-render.js's own onClick, lifted out of the file
// whole and run against the stubs it calls; the click is dispatched at the
// card's box (the element a finger lands on) and bubbles up to the picture.
function composerOnClick(calls) {
    const src = fs.readFileSync(path.join(__dirname, 'composer-render.js'), 'utf8');
    const at = src.indexOf('function onClick(e) {');
    if (at < 0) throw new Error('composer-render.js has no onClick; update composerOnClick');
    let depth = 0, end = -1;
    for (let i = src.indexOf('{', at); i < src.length; i++) {
        if (src[i] === '{') depth++;
        else if (src[i] === '}' && --depth === 0) { end = i + 1; break; }
    }
    // THE POSITIONS SCREEN (pick-a-part U4) is the station's one tappable
    // picture: a card taps its position, a staging slot or lane taps the LANE
    // (so a slot can be moved onto it), and the dock is not a target.
    const ctx = {
        screen: 'positions',
        onPositionsTap(n) { calls.push('tap:' + n); },
    };
    vm.createContext(ctx);
    vm.runInContext(src.slice(at, end) + '\n__h = onClick;', ctx);
    return ctx.__h;
}
